#!/usr/bin/env python3
"""Convert the approved white-on-black R15 wordmark to a compact A8 mask."""
from pathlib import Path
import hashlib
import json
from PIL import Image

root = Path(__file__).resolve().parent.parent
output = root / "assets/animations/lvgl/r15_signature.c"
size = (192, 64)
# The source is intentionally opaque: luminance becomes coverage. Black is
# transparent and white becomes an antialiased, recolorable alpha mask.
image = Image.open(root / "assets/animations/source/r15-signature.png").convert("L")
# Pack the generated mark without wasting its native display size on black
# source padding. Preserve letter geometry/aspect; reserve a 16-pixel side margin.
bounds = image.point(lambda value: 255 if value >= 32 else 0).getbbox()
if not bounds:
    raise RuntimeError("R15 source contains no visible wordmark")
image = image.crop(bounds)
image.thumbnail((160, 40), Image.Resampling.LANCZOS)
mask = Image.new("L", size, 0)
mask.paste(image, ((size[0]-image.width)//2, (size[1]-image.height)//2))
payload = mask.tobytes()
lines = ["/* Generated by scripts/generate-animation-assets.py; do not edit. */",
         '#include "lvgl.h"', "static const uint8_t image_data[] = {"]
for i in range(0, len(payload), 24):
    lines.append("    " + ",".join(f"0x{x:02x}" for x in payload[i:i+24]) + ",")
lines += ["};", "const lv_image_dsc_t r15_signature = {",
          "    .header = { .magic=LV_IMAGE_HEADER_MAGIC, .cf=LV_COLOR_FORMAT_A8,",
          f"        .w={size[0]}, .h={size[1]}, .stride={size[0]} }},",
          "    .data_size=sizeof(image_data), .data=image_data", "};", ""]
output.write_text("\n".join(lines))
print("r15_signature:", len(payload), "bytes")

base = root / "assets/animations"
manifest = {
    "generator": "built-in image_gen.imagegen",
    "concept": "02 R15 Light Signature",
    "conversion": "scripts/generate-animation-assets.py",
    "pillow": "12.3.0",
    "format": "192x64 A8 luminance mask; aspect-preserving 160x40 content fit",
    "sha256": {str(path.relative_to(base)): hashlib.sha256(path.read_bytes()).hexdigest()
               for path in [base / "source/r15-signature.png", output]},
}
(base / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
